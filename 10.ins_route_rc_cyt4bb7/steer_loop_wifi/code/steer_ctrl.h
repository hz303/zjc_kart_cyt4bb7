    uint8   fault;              /* ★锁存故障位: STEER_FLT_ENC（置位后输出被钉 0）, 0 = 正常 */
    uint32  enc_bad_ms;         /* 坏样的累计时间（**漏水积分**：坏样 +5ms、好样 -5ms） */

    /* --- ★ 反馈失效的自动复位（见本文件顶部 STEER_ENC_AR_*）--- */
    uint32  ar_ms;              /* 链路连续干净的累计时间 */
    uint32  ar_win_ms;          /* 窗口剩余时间（到 0 才允许 ar_tries 归零、重新试） */
    uint8   ar_tries;           /* 本窗口内已自动复位的次数 */
