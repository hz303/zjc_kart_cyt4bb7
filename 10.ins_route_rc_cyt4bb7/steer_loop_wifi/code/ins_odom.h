/*********************************************************************************************************************
 * C 车惯导 + 路表 - 航位推算（IMU 航向 × 编码器里程 → 米制位姿）
 *
 * ★ 算法本体只有 8 行，来自国二工程 `Polaris-Kart-TC387` 的 `code/Kart_App/kart_odom.c:60-85`：
 *
 *      yaw  <- IMU 的累积航向（度）
 *      ds   <- 左右编码器各自换算成米，取车体中心
 *      x    += -sin(yaw) * ds          // x = 向右
 *      y    +=  cos(yaw) * ds          // y = 向前（= 录制起点朝向）
 *
 *   坐标约定（照搬 Polaris，**与上位机渲染强耦合，改一处必须同步改上位机**）:
 *      yaw = 0 时车头朝 +Y；yaw 增大（左转）朝 -X 转
 *      ⇒ x = 车头朝前时的**右手**方向, y = **向前**
 *      ⇒ 上位机: screen_x ∝ x, screen_y ∝ -y
 *
 * ---- ★★ 相对 Polaris 修掉的缺陷（它的技术报告自己承认过）-----------------------------
 *   1. **`dist_sum += fabsf(ds)`** —— Polaris 用它当里程，结果"**倒车时打滑会被当成前进**"，
 *      技术报告里倒车段实测 yaw 漂 11°。
 *      本工程: `ds` **带符号**（前进正、后退负），位置积分用带符号的 ds；
 *              总路程另用一个 fabsf 的累加器 `dist_abs`。**两者不要混。**
 *   2. **位姿快照要原子取** —— `ins_odom_update()` 在 5ms 中断里跑，消费者在主循环。
 *      分三次 get x/y/yaw 会被中断插到半路，拿到"旧 x + 新 yaw"的撕裂值。
 *      Polaris 用 `interrupt_global_disable()` 复制 4 个字段（`kart_odom.c:97-112`）。
 *      ⚠⚠ **但不要照样抄它的临界区写法**：逐飞的 `interrupt_global_disable()` /
 *      `interrupt_global_enable(pm)` **不是保存/恢复 PRIMASK**（那是个被 `clock_init` 和 `main`
 *      各加过一次的计数器，`enable` 只在参数为 0 时才真的 `__enable_irq()`）⇒
 *      `pm = disable(); ...; enable(pm);` 会把中断**永久关死且零报错**。
 *      本工程改成了 `ins_crit_enter()/ins_crit_exit()`（直接存取 PRIMASK），见 ins_odom.c 顶部注释。
 *   3. **"只用相对量"的纪律** —— yaw 会漂，所以录制与复现必须共用同一基准。
 *      ⇒ `ins_route` 头部存 `origin_x / origin_y / origin_yaw`（见 ins_route.h）。
 *
 * ---- 比例尺：从"待测"到"实测" --------------------------------------------------------
 *   距离的来源是 `k_m`（每计数多少米）:
 *        k_m = m_per_rev / cpr
 *   其中 `m_per_rev` 是**唯一需要按实车改的数字**（见 motor_link.h 的参数表 `ins_m_per_rev`）。
 *
 *   ⚠ 历史坑（保留以免再犯）：早先用的是**占位值 1.0**（用户给的「1 rps = 1 m/s」，
 *     等价轮周长 1.000 m / 轮径 Ø318.3 mm）⇒ **把距离放大了 11.2 倍**。
 *     因为是全局等比缩放，**轨迹形状、航向、相对弯曲全都正确，只有"米"这个单位是错的**
 *     —— 这正是"实际轨迹像梨形、首尾收不回来"里"尺度"那一份的来源。
 *   ✅ **工程 10（卡丁）2026-10-15 已实测定稿**：`INS_MPM_DEFAULT = 0.8193`（来源见下方定义处）。
 *      上面那条"放大 11.2 倍"是**工程 8（C 车）**的历史；C 车的定稿值是 0.0895。
 ********************************************************************************************************************/

#ifndef _INS_ODOM_H
#define _INS_ODOM_H

#include "zf_common_headfile.h"

/*===================================================================================================================
 *  参数（参数表取地址，见 motor_link.h）
 *=================================================================================================================*/
/* ★ 米/（编码器）转 —— 唯一的比例尺参数。
   真实值 = 2π × 轮半径 ÷ 减速比（编码器在电机轴、中间有减速箱时）。
   实测法（菜单 `EncCal1m` / `EncCal2m`）：清零 → 沿直线推车整 1.00 / 2.00 m →
                                          m_per_rev = 距离 × cpr / 累计计数。 */
#define INS_MPM_DEFAULT     (0.8193f)
/*   ↑ ★★ **2026-10-15 实测定稿 = 0.8193**（工程 10 的卡丁；旧占位 0.7540 已作废）。
 *
 *   怎么来的：地面量 **2.815 m**、手推直线，编码器累计 `pos_l = 6352 / pos_r = 6415 cnt`
 *   （参考点 = **两个后轮的中部**，与航位推算取"左右平均"一致）⇒
 *       `m_per_rev = cpr × D / 计数 = 1858 × 2.815 / 6383.5 = 0.81934`。
 *   交叉校验：同批另一组（**3.000 m** / 平均 6865 cnt，参考点取"左后轮尾部"）得 0.8119，
 *   **两组差 0.90%** ⇒ 尺度可信；按用户判定**以 2.815 m 那组为准**（参考点更对）。
 *
 *   ⚠ 前提 = `cpr = 1858`（1024 线 / 脉冲+方向，经 49:27 增速，见工程 9 `motor_link.h`）。
 *     **若车上 `cpr_l/cpr_r`(ID8/ID9) 被改过，本值必须按同比例跟着改**（不变量始终是 `mpm/cpr`）。
 *   物理含义：**轮子与电机同轴** ⇒ `m_per_rev` 就等于**后轮周长** ⇒ 等效轮径 **Ø260.8 mm**
 *   （π×0.2608 = 0.8192 ✓，比 Polaris 的 Ø240 大，与卡丁尺寸相符）。
 *
 *   —— 复标法（卡丁没有屏幕没有按键，走上位机）——
 *     ① 地面量好 **2.0 ~ 3.0 m**（⭐ 别用 1 m：C 车实测 σ 从 1.27% 降到 0.85%）
 *     ② 清零 `pos_l/pos_r` → 沿直线推车走完全程（参考点取**两后轮中部**）
 *     ③ 读 `pos_l / pos_r`，取平均 `N` ⇒ `ins_mpm_新 = 1858 × 距离 / N`（填回 ID 34）
 *     ⚠ 推车标定的地板约 **0.66%**（打滑），再准只能靠"电机驱动标定"或"整圈 + 地图真值"。
 *     ⚠ 它只影响"米"这个单位：尺度错了**轨迹形状与航向仍然对**，只是米数整体差 k 倍。 */
extern volatile float    ins_m_per_rev;

/* 航位推算使能（0 = 冻结积分，只跟踪基准；标定/静止时用） */
extern volatile float    ins_odom_enable;

/* 打滑判据: 左右计数增量之差超过该比例、且航向几乎没变 ⇒ 置"打滑"标志（**只报警不改数据**） */
extern volatile float    ins_slip_pct;

/* ★ 工程 10 新增：位姿归零命令（参数表 ID 37）。**0→1 边沿触发一次**：
   `ins_odom_reset()` + `ins_imu_zero_yaw()`（位姿与航向必须一起归，见 ins_odom.c 的定义处注释）。
   ⚠ 边沿处理放**主循环**（慢速决策层），别放 5ms 中断；
     与工程 9 的 `steer_en` / `ol_en` 是同一套写法（改完参数要拖回 0 才能再触发）。 */
extern volatile float    ins_zero_cmd;

/*===================================================================================================================
 *  状态位（遥测 ins_flags 的低 8 位）
 *=================================================================================================================*/
#define ODOM_ST_ACTIVE      (0x01u)     /* 正在积分                       */
#define ODOM_ST_STILL       (0x02u)     /* 连续 N 拍两轮都没动（静止）     */
#define ODOM_ST_SLIP        (0x04u)     /* 本拍判定打滑                   */

/*===================================================================================================================
 *  接口
 *=================================================================================================================*/
void    ins_odom_init       (void);
void    ins_odom_update     (void);         /* 5ms 每拍：吃编码器 Δcnt + yaw → (x,y) */
void    ins_odom_reset      (void);         /* 位置/里程清零（并刷新基准）*/
void    ins_odom_set_origin (float x, float y, float yaw_deg);  /* 设当前点为指定位姿 */

float   ins_odom_get_x      (void);
float   ins_odom_get_y      (void);
float   ins_odom_get_yaw    (void);
float   ins_odom_get_dist   (void);         /* 累计路程（标量，m）        */
float   ins_odom_get_v_mps  (void);         /* 本拍车速（m/s，带符号）    */
float   ins_odom_get_km     (void);         /* 当前生效的米/计数（诊断用）*/
uint8   ins_odom_flags      (void);

/* 一致位姿快照（原子，见上面缺陷 2） */
typedef struct
{
    float x;            /* 米，向右    */
    float y;            /* 米，向前    */
    float yaw;          /* 度，相对起点，累积可超 ±360 */
    float dist_abs;     /* 累计路程（标量，m）        */
    float v_mps;        /* 本拍车速（m/s，带符号）    */
    uint8 flags;        /* ODOM_ST_*                  */
} ins_odom_snap_t;

void    ins_odom_snapshot   (ins_odom_snap_t *out);

#endif
