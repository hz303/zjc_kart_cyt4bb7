/* 工程 10（卡丁）· 参数持久化（把参数表整张存进 Flash 页 0）
 * 车端 `MOTOR_CMD_SAVE` **只回 ACK、不写 Flash**（见 motor_link.c）。
 * 所以在这之前：**每次上电，`k_v/k_z/ins_mpm/转向限位/开环 duty` 全部回到源码默认值**，
 * 要么靠上位机重新下发一遍，要么改源码重烧。本模块就是"车端自己记住"的那一层。
 * ---- 做法（**表驱动，不写死任何字段名**）-------------------------------------------------
 * 元数据来自 `proto.c`（唯一源在 `param_table.h`），每一行是
 * X(id, 名字, 中文名, lo, hi, 默认值, 单位, 步长, 指针, PERM, GROUP)
 * ⇒ 存 = 顺着 `proto_param_at(i)` 把 `*ptr` 逐个复制下来；
 * 读 = 逐个写回，并且**按每行自己的 lo/hi 做范围校验**（越界的那个字段保持默认值，其余照收）。
 * ⇒ **以后往参数表里加 ID，本模块自动跟着走，不用改一行。**
 * 凡是 `PERM == P_CMD`（目标/使能/录制/回放/测试…）一律"不恢复、存默认值"；
 * 这是"命令不许持久化"的唯一表达 —— 加一个命令参数时只要在表里标 P_CMD，
 * 绝不会再出现"忘了加黑名单 ⇒ 下次上电自己触发一次归零/自动使能"。
 * ---- 载荷格式（页 0）-------------------------------------------------------------------
 * magic('KPZ1') | version | count | crc16(载荷) | rsvd | float val[count]
 * 校验：magic + count 必须与当前表一致 + **CRC16-MODBUS** 对载荷校验。
 * 这一条是防"参数表插队/删项"导致**静默错位**。
 * **512 字节**（= 128 个 uint32），而 buffer 实际 2048 字节。
 * 当前载荷 = 12 B 头 + 76 x 4 B = **316 B = 79 个 uint32** ⇒ 在 128 以内，不受影响。
 * 上限是 `APP_PARAM_MAX = 96` 项（= 99 words = 396 B）**仍在 128 以内**；
 * **以后若把载荷加到 128 个 uint32 以上，必须自己补 memset。**
 */

#ifndef _APP_PARAMS_H
#define _APP_PARAMS_H

#include "zf_common_headfile.h"
#include "proto.h"

/* 参数表已经长到 76 项（ID 0~75），而旧值是 64 —— `float val[64]` 后面再写 12 项，
 * 等于**每次上电/每次存盘都越界写 48 字节栈**。这个 bug 不报错，只会表现成
 * "存完参数后有些变量自己变了 / 偶尔跑飞"，属于最难查的那一类。
 * ⇒ 现在上限与协议层同源，表再长也不会溢出（proto.c 里有编译期护栏）。
 */
#define APP_PARAM_MAX       (PROTO_PARAM_MAX)
/* 旧固件在 76 项表 + 64 项缓冲下存出来的块**本身就是坏的**（写越界，CRC 覆盖到栈垃圾，
 * 代价 = 用户上一次存的参数丢失（那份数据本来也不可信）；收益 = 不会把栈垃圾当参数用。
 */
#define APP_PARAM_VERSION   (2u)

/* 上电读一次：放在各模块 init 之后、开 5ms 中断之前。失败时保持源码默认值。 */
void    app_param_init      (void);

/* 把当前运行参数写进 Flash（擦+写，**阻塞几十 ms**）⇒ 只能在主循环里调、且要带去抖。 返回 0 = 成功（含读回校验），非 0 = 失败码 */
uint8   app_param_save      (void);

/* 是否成功从 Flash 载入过有效数据（0 = 用的是源码默认值） */
uint8   app_param_loaded    (void);

/* 把"当前运行参数"重置为源码默认值（**不写 Flash**） */
void    app_param_restore_defaults (void);

/* 上一次载入/保存的诊断码（0 = OK） */
uint8   app_param_last_err  (void);

#endif
