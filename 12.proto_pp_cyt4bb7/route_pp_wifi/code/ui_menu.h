/* 工程 10（卡丁）· 屏幕菜单（IPS200 竖屏 240x320 + 主板 4 键）
 * 来源：工程 8 `ui_menu.c` 的**状态机与观感**（K1=确认 / K2=返回 / K3=上? 见下 / K4=下、
 * 长按 100 ms 连按一步、`UI_ONDEMAND` 空闲零 SPI）；**菜单内容按卡丁重写**：
 * 工程 8 那一串是路表/录制/巡航/舵机，卡丁这边要的是"一键跑班 + 速调增益 + 存参数"。
 * ---- 键位（与工程 8 一致）--------------------------------------------------------------
 * K1 = 确认/进编辑       K2 = 返回/退编辑
 * K3 = 光标下移          K4 = 光标上移
 * ---- 三个页面 --------------------------------------------------------------------------
 * LIST  16 项菜单（静态内容：只在**有按键那一拍**重画 ⇒ 空闲时屏幕 SPI 完全静默）
 * EDIT  改一个参数（K3/K4 按参数自己的步长加减，K1 生效并返回）
 * DASH  仪表盘（走 ui_core 的字段引擎，**逐字段比对缓存，变了才画**）
 * 车端 `MOTOR_CMD_SAVE` **只回 ACK、不写 Flash**。没有这一项的话，每次上电
 * `k_v/k_z/ins_mpm/转向限位` 全部回到源码默认值。本工程的 `app_params` + 这一项
 * 就是"车端自己记住"的那一层（存 Work Flash 页 0）。
 */

