/*===================================================================================================================
 *  四、通道下标(motor_link_ch_set 用的就是这些值)
 *
 *  ⚠ 顺序即协议: 与上位机「双电机速度环」档案一一对应, 改顺序 = 改协议。
 *=================================================================================================================*/
