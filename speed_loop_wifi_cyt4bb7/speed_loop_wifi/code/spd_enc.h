/*********************************************************************************************************************
 * 双电机速度环(WiFi) - 增量式编码器测速(脉冲 + 方向), 双通道
 *
 * 用途: 把"脉冲/方向"式编码器在 5ms 定周期里变成可用的转速 rps。左右各一个实例。
 *
 * ---- 接线(逐飞 CYT4BB7 主板标准接口, 与库例程 E2_01_encoder_dir_demo 一致) ----------
 *      左编码器:  PULSE -> P17_3 (TC_CH58 的 CH1)     DIR -> P17_4 (TC_CH58 的 CH2)
 *      右编码器:  PULSE -> P19_2 (TC_CH27 的 CH1)     DIR -> P19_3 (TC_CH27 的 CH2)
 *      GND -> GND,  电源按模块丝印(P17_3/P17_4 与 MM32 那边的 B4/B5 是同一组信号)
 *
 * ---- 必须知道的库实现细节(决定了本模块为什么这么写) --------------------------------
 *  逐飞 encoder_dir_init() 把 TCPWM 配成"每条脉冲 +1"的单向计数器, 定时器本身不记方向;
 *  方向是靠 encoder_get_count() 里"读的那一刻取 DIR 引脚电平, 再把整个计数值取反"得到的。
 *  后果: 只要 DIR 电平在两次采样之间变过, "当前读数 - 上次读数"就是错的
 *        (例: 上次 +1000, 换向后 -1050 -> 差分 -2050, 实际只倒退了 50)。
 *  对策: 本模块检测 DIR 电平变化, 那一拍的速度直接记 0(换向必经过 0 速, 是最接近真值的估计),
 *        并把事件计入 flip 计数。代价: 换向瞬间丢 1 拍(5ms)速度信息。
 *
 *  ---- 每转计数必须实测标定(别照抄) ---------------------------------------------------
 *  本车实测: 编码器 1024 线(只数上升沿) + 电机轴 49 齿带动 27 齿(增速 49/27)
 *  => 每【电机转】计数 = 1024 * 49/27 = 1858 (轮子与电机同轴, 所以这也是每轮转计数)
 *  标定方法: 清零 pos -> 单方向手转【电机轴】整 10 圈 -> cpr = pos 增量 / 10
 *  上位机可直接改 cpr_l / cpr_r, 不用重烧。
 ********************************************************************************************************************/

#ifndef _SPD_ENC_H
#define _SPD_ENC_H

#include "zf_common_headfile.h"

/*===================================================================================================================
 *  一、接线与滤波参数
 *=================================================================================================================*/
/* --- 左编码器(编码器1) --- */
#define ENC_L_INDEX         (TC_CH58_ENCODER)
#define ENC_L_PULSE_PIN     (TC_CH58_ENCODER_CH1_P17_3)
#define ENC_L_DIR_PIN       (TC_CH58_ENCODER_CH2_P17_4)
#define ENC_L_DIR_GPIO      (P17_4)             /* 同一根 DIR 线对应的 GPIO, 用来直接读电平 */

/* --- 右编码器(编码器2) --- */
#define ENC_R_INDEX         (TC_CH27_ENCODER)
#define ENC_R_PULSE_PIN     (TC_CH27_ENCODER_CH1_P19_2)
#define ENC_R_DIR_PIN       (TC_CH27_ENCODER_CH2_P19_3)
#define ENC_R_DIR_GPIO      (P19_3)

#define ENC_PERIOD_MS       (5)                 /* 采样周期, 必须与控制环一致(5ms -> 200Hz) */
#define ENC_T_S             (0.005f)
#define ENC_WIN             (4)                 /* 滑动平均窗口【默认值】(1 = 不滤波)。4 -> 等效 20ms 均值 */
#define ENC_WIN_MAX         (16)                /* 窗口上限(缓冲按它开; 实际用多少由 spd_enc_win 决定) */

/* ★★ DIR 去抖 + 读数毛刺门限 (2026-10-01 加, 治"v 里周期性 0.3~0.7 rps 的假凹陷")
 *
 *  旧逻辑是"DIR 一变就丢一整拍"。它的致命处:
 *    一次【1 拍】的电气毛刺(电平跳走又跳回)会被判成【两次】变化
 *    => 连丢 2 拍 => 4 拍窗口掉 23 个计数 => v 上出现 0.7 rps 的假凹陷。
 *    (1.4 rps 时每拍 11.5 个计数, 丢 1 拍 = 0.35 rps)
 *
 *  新逻辑: 新电平必须【连续 ENC_DIR_DEBOUNCE 拍】都一致才认换向; 认之前沿用旧方向。
 *    真换向只是"晚 2 拍(10ms)认出来" —— 而换向必然经过 0 速, 那几拍计数本来就少,
 *    所以这个滞后几乎不损失精度。= 1 时最接近旧行为。
 *
 *  ENC_DLT_GLITCH_MAX: 单拍原始计数增量超过它就判为"读数毛刺"并丢掉这一拍。
 *    典型来源: 库的 encoder_get_count() 内部读 DIR 的那一刻, 电平与我们读的差了,
 *    符号被翻 -> 差分成 ±2×当前计数 的假尖峰(在 v 上会被窗口摊成巨大凹陷)。
 *    400 cnt / 5ms = 43 rps, 远高于任何真实转速, 不会误杀。 */
#define ENC_DIR_DEBOUNCE        (2)
#define ENC_DLT_GLITCH_MAX      (400)

/* 每电机转计数的默认值(实测值, 上位机可在线改) */
#define ENC_CPR_DEFAULT     (1858.0f)

/*===================================================================================================================
 *  二、一路编码器的实例(左右各一个)
 *=================================================================================================================*/
typedef struct
{
    encoder_index_enum      idx;            /* 定时器通道                       */
    encoder_channel1_enum   pulse_pin;      /* 脉冲脚(配置成计数输入)           */
    encoder_channel2_enum   dir_pin;        /* 方向脚(库会配成 GPIO 输入)       */
    gpio_pin_enum           dir_gpio;       /* 方向脚对应的 GPIO 号(读电平用)   */

    volatile float  cpr;                    /* 每转计数(可在线改)               */
    volatile float  invert;                 /* >0.5 = 测速取反(可在线改)        */

    volatile int16  last_raw;               /* 上次的【原始计数】(未加符号)     */
    volatile uint8  last_dir;               /* 去抖之后的 DIR 电平              */
    volatile uint8  dir_pend;               /* 待确认的新 DIR 电平              */
    volatile uint8  dir_pend_cnt;           /* 新电平已连续出现几拍             */
    volatile int16  delta;                  /* 本拍计数增量(带符号)             */
    volatile int32  pos;                    /* 累计计数(带符号)                 */
    volatile float  raw_rps;                /* 本拍单点转速(未滤波)             */
    volatile float  rps;                    /* 滤波后转速 rps                   */
    volatile uint32 flip;                   /* 真换向次数(去抖确认后)           */
    volatile uint32 glitch;                 /* 读数毛刺丢弃次数                 */
    volatile uint32 samples;                /* 总采样拍数(应匀速增长)           */

    uint8           win_n_used;             /* 上次实际用的窗口长度(变了就重建缓冲) */

    int16           win[ENC_WIN_MAX];       /* 滑动平均缓冲(按上限开)            */
    uint32          win_cnt;
    int32           win_sum;
} spd_enc_t;

extern spd_enc_t enc_l;
extern spd_enc_t enc_r;

/* ★ 测速滤波窗口长度(在线可调, 1~ENC_WIN_MAX)。两路共用 —— 编码器同型号,
 *   而且它是"滤波器"不是硬件参数。
 *   等效延迟 = (win_n - 1) / 2 * 5ms  ⇒ win_n=4 -> 7.5ms, win_n=8 -> 17.5ms
 *   噪声按 1/sqrt(win_n) 降 ⇒ 4->8 噪声降约 30%, 代价是相位裕度被吃掉一部分
 *   (加长窗口后要把 k_v 相应调小, 否则会振)。
 *   ⚠ 窗口一改, 缓冲会重建, 会有 1 拍过渡。 */
extern volatile float spd_enc_win;

/*===================================================================================================================
 *  三、接口
 *=================================================================================================================*/
void    spd_enc_init        (void);                 /* 两路一起初始化, 并预读初值 */
void    spd_enc_update      (spd_enc_t *e);         /* 5ms 调一次(放 PIT 中断里)  */
void    spd_enc_reset_pos   (spd_enc_t *e);         /* 清累计计数(标定 cpr 前用)  */

#endif
